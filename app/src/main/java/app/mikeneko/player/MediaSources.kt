/** Une piste de sous-titres proposée dans les réglages. */
data class CaptionTrack(
    val id: String,
    val language: String,
    val label: String,
    val auto: Boolean,
    internal val url: String,
    internal val mimeType: String,
)

/** Transforme un StreamInfo de NewPipe en source jouable par ExoPlayer. */
@OptIn(UnstableApi::class)
object MediaSources {

    /** Pour savoir si la connexion est illimitée (Wi-Fi) : rempli par PlayerHolder.init. */
    internal var appContext: Context? = null

    /**
     * Qualité « Auto ». En Wi-Fi (2.9.0) : le palier YouTube au-dessus de la résolution de l'écran,
     * comme l'appli YouTube (1440p sur un écran de 1264 lignes) : un débit bien plus haut, réduit à
     * la taille de l'écran, donne des scènes sombres propres (en 1080p, elles se voyaient en blocs).
     * En données mobiles : jusqu'à la résolution de l'écran, comme avant. Jamais sous 720p ni
     * au-dessus de 1440p.
     */
    val autoMaxHeight: Int
        get() {
            val metrics = Resources.getSystem().displayMetrics
            val screen = minOf(metrics.widthPixels, metrics.heightPixels)
            val unmetered = appContext?.let { context ->
                runCatching { context.getSystemService(ConnectivityManager::class.java)?.isActiveNetworkMetered == false }.getOrNull()
            } ?: false
            val limit = if (unmetered) TIERS.firstOrNull { it >= screen } ?: screen else screen
            return limit.coerceIn(720, 1440)
        }

    /** La source à jouer, et la hauteur vidéo réellement choisie (0 pour l'audio seul / le direct). */
    class Built(val source: MediaSource, val height: Int, val audioKey: String? = null, val videoKey: String? = null)

    fun isLive(info: StreamInfo) =
        info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM

    /** Les qualités proposées pour cette vidéo, de la meilleure à la moins bonne (ex. 1080, 720, 480…). */
    fun qualities(info: StreamInfo): List<Int> =
        (playableVideoOnly(info) + playableMuxed(info))
            .map { it.shortSide }
            .filter { it > 0 }
            .distinct()
            .sortedDescending()

    /**
     * Les sous-titres disponibles, d'abord ceux écrits à la main. YouTube (via NewPipe) les donne
     * en WebVTT et/ou TTML selon les vidéos : ExoPlayer lit les deux, on préfère WebVTT.
     */
    fun captions(info: StreamInfo): List<CaptionTrack> =
        info.subtitles
            .filter { it.isUrl && (it.format == MediaFormat.VTT || it.format == MediaFormat.TTML) }
            .sortedBy { if (it.format == MediaFormat.VTT) 0 else 1 }
            .distinctBy { it.languageTag to it.isAutoGenerated }
            .sortedWith(compareBy<SubtitlesStream> { it.isAutoGenerated }.thenBy { it.displayLanguageName })
            .map {
                CaptionTrack(
                    id = it.languageTag + if (it.isAutoGenerated) "#auto" else "",
                    language = it.languageTag.substringBefore('-').lowercase(),
                    label = it.displayLanguageName.replaceFirstChar { c -> c.uppercase() } +
                        if (it.isAutoGenerated) AppLocale.string(R.string.captions_auto_suffix) else "",
                    auto = it.isAutoGenerated,
                    url = it.content,
                    mimeType = if (it.format == MediaFormat.VTT) MimeTypes.TEXT_VTT else MimeTypes.APPLICATION_TTML,
                )
            }

    /**
     * @param maxHeight qualité voulue (la meilleure en dessous si elle n'existe pas) ; null = Auto.
     * @param caption sous-titres à charger avec la vidéo ; null = aucun.
     */
    /**
     * @param cache la sauvegarde hors ligne où passent les flux ([OfflineCache]) ; null = sans cache.
     */
    fun build(info: StreamInfo, audioOnly: Boolean, maxHeight: Int? = null, caption: CaptionTrack? = null, cache: SimpleCache? = null): Built {
        val http = DefaultHttpDataSource.Factory()
            .setUserAgent(NewPipeDownloader.USER_AGENT)
            .setAllowCrossProtocolRedirects(true)
        val metadata = MediaMetadata.Builder()
            .setTitle(info.name)
            .setArtist(info.uploaderName)
            .setArtworkUri(info.thumbnails.maxByOrNull { it.height }?.url?.toUri())
            .build()

        fun item(uri: String, mime: String? = null, key: String? = null) = MediaItem.Builder()
            .setUri(uri)
            .setMediaId(info.url)
            .setMediaMetadata(metadata)
            .apply { if (mime != null) setMimeType(mime) }
            .apply { if (key != null) setCustomCacheKey(key) }
            .build()

        val hls = info.hlsUrl
        if (isLive(info) && !hls.isNullOrBlank()) {
            // En direct, la qualité se règle sur les pistes HLS (voir PlayerHolder.setQuality)
            return Built(HlsMediaSource.Factory(http).createMediaSource(item(hls, MimeTypes.APPLICATION_M3U8)), 0)
        }

        // Vidéo et audio lus par morceaux : YouTube bride les longues requêtes (voir ChunkedDataSource)
        // et gardés dans la sauvegarde hors ligne, sous une clé stable « id:itag » (les adresses changent)
        val plain = ChunkedDataSource.Factory(http)
        val chunked = if (cache != null) OfflineCache.factory(cache, plain) else plain
        val progressive = ProgressiveMediaSource.Factory(chunked)
        val audio = bestAudio(info.audioStreams)
        fun keyOf(kind: Char, itag: Int) = if (cache != null) OfflineCache.key(info.id, kind, itag) else null
        val audioKey = audio?.let { keyOf('a', it.itag) }

        if (audioOnly && audio != null) {
            return Built(progressive.createMediaSource(item(audio.content, key = audioKey)), 0, audioKey)
        }

        val limit = maxHeight ?: autoMaxHeight
        val muxed = bestVideo(playableMuxed(info), limit)
        val videoOnly = audio?.let { bestVideo(playableVideoOnly(info), limit) }

        val (videoUri, height, needsAudio) = when {
            videoOnly != null && videoOnly.shortSide > (muxed?.shortSide ?: 0) -> Triple(videoOnly.content, videoOnly.shortSide, true)
            muxed != null -> Triple(muxed.content, muxed.shortSide, false)
            else -> error(AppLocale.string(R.string.no_playable_stream))
        }
        val videoKey = if (needsAudio) videoOnly?.let { keyOf('v', it.itag) } else muxed?.let { keyOf('m', it.itag) }

        // La vidéo (+ ses sous-titres, ajoutés par DefaultMediaSourceFactory qui sait les lire)
        val videoItem = MediaItem.Builder()
            .setUri(videoUri)
            .setMediaId(info.url)
            .setMediaMetadata(metadata)
            .apply { if (videoKey != null) setCustomCacheKey(videoKey) }
            .apply {
                if (caption != null) {
                    setSubtitleConfigurations(
                        listOf(
                            MediaItem.SubtitleConfiguration.Builder(caption.url.toUri())
                                .setMimeType(caption.mimeType)
                                .setLanguage(caption.language)
                                .setLabel(caption.label)
                                .setSelectionFlags(C.SELECTION_FLAG_DEFAULT)
                                .build(),
                        ),
                    )
                }
            }
            .build()
        val video = if (caption != null) DefaultMediaSourceFactory(chunked).createMediaSource(videoItem) else progressive.createMediaSource(videoItem)

        val source = if (needsAudio && audio != null) {
            val audioItem = MediaItem.Builder().setUri(audio.content).apply { if (audioKey != null) setCustomCacheKey(audioKey) }.build()
            MergingMediaSource(video, progressive.createMediaSource(audioItem))
        } else {
            video
        }
        // Hors ligne, l'entrée garde la piste principale en « audio » : le son, ou le flux vidéo+son
        return if (needsAudio) Built(source, height, audioKey, videoKey) else Built(source, height, videoKey, null)
    }

    /** À hauteur égale : le codec le plus léger que le téléphone décode en matériel (voir codecRank), puis le plus fluide. */
    /**
     * La meilleure vidéo jusqu'à [limit] : la plus haute résolution ; à résolution égale, un flux que le
     * téléphone décode en matériel, puis **le plus gros débit** (2.9.0 : avant, le codec d'abord,
     * et l'AV1 de YouTube, souvent au débit le plus bas, faisait des blocs dans les scènes sombres).
     */
    private fun bestVideo(streams: List<VideoStream>, limit: Int) =
        streams.filter { it.shortSide <= limit }
            .maxWithOrNull(compareBy<VideoStream>({ it.shortSide }, { codecRank(it) >= 3 }, { it.bitrate }, { codecRank(it) }, { it.fps }))
            ?: streams.minByOrNull { it.shortSide } // rien d'assez petit : la plus petite disponible

    /** Ce qu'il faut télécharger pour garder une vidéo / un morceau hors ligne (mêmes choix et mêmes clés que [build]). */
    class Plan(val audioKey: String, val audioUrl: String, val videoKey: String?, val videoUrl: String?, val height: Int)

    fun downloadPlan(info: StreamInfo, audioOnly: Boolean, maxHeight: Int?): Plan {
        val audio = bestAudio(info.audioStreams)
        fun key(kind: Char, itag: Int) = OfflineCache.key(info.id, kind, itag)
        if (audioOnly) {
            audio ?: error(AppLocale.string(R.string.no_playable_stream))
            return Plan(key('a', audio.itag), audio.content, null, null, 0)
        }
        val limit = maxHeight ?: autoMaxHeight
        val muxed = bestVideo(playableMuxed(info), limit)
        val videoOnly = audio?.let { bestVideo(playableVideoOnly(info), limit) }
        return when {
            videoOnly != null && audio != null && videoOnly.shortSide > (muxed?.shortSide ?: 0) ->
                Plan(key('a', audio.itag), audio.content, key('v', videoOnly.itag), videoOnly.content, videoOnly.shortSide)
            muxed != null -> Plan(key('m', muxed.itag), muxed.content, null, null, muxed.shortSide)
            else -> error(AppLocale.string(R.string.no_playable_stream))
        }
    }

    /** Le palier YouTube du flux (1080 pour du 1920×1078, du 1920×800 ou du 1080×1920). */
    private val VideoStream.shortSide: Int
        get() = qualityTier(width, height)

    private val TIERS = intArrayOf(144, 240, 360, 480, 720, 1080, 1440, 2160, 4320)
    private val LONG_SIDES = intArrayOf(256, 426, 640, 854, 1280, 1920, 2560, 3840, 7680)

    /**
     * Le « 1080p » qu'afficherait YouTube pour une image [width]×[height] : on prend le palier
     * standard atteint par le petit côté OU par le grand côté (marge de 16 px pour les encodages
     * à 1078 ou 1088 lignes). Ainsi 1920×1078 → 1080, 1920×800 (cinéma) → 1080, 1080×1920
     * (vertical) → 1080, 1080×1080 (carré) → 1080, 1440×1080 (4:3) → 1080.
     */
    fun qualityTier(width: Int, height: Int): Int {
        if (width <= 0 || height <= 0) return maxOf(width, height, 0)
        val short = minOf(width, height)
        val long = maxOf(width, height)
        val byShort = TIERS.firstOrNull { it >= short - 16 } ?: TIERS.last()
        val byLong = LONG_SIDES.indexOfFirst { it >= long - 16 }.let { if (it < 0) TIERS.last() else TIERS[it] }
        return maxOf(byShort, byLong)
    }

    /**
     * Vidéo seule que ce téléphone sait lire : H.264 (jusqu'en 1080p chez YouTube), VP9 et AV1
     * (1440p, 4K…). Au-dessus de 1080p, il faut un décodeur matériel, sinon la vidéo saccade
     * et la batterie fond. Les flux HDR (10 bits) sont écartés : délavés sur un écran normal.
     */
    private fun playableVideoOnly(info: StreamInfo): List<VideoStream> =
        info.videoOnlyStreams.filter { stream ->
            if (!stream.isUrl) return@filter false
            val mime = mimeOf(stream) ?: return@filter false
            if (isHdr(stream)) return@filter false
            val (w, h) = (stream.width to stream.height).takeIf { it.first > 0 && it.second > 0 } ?: return@filter mime == MimeTypes.VIDEO_H264
            Decoders.supports(mime, w, h, stream.fps, needHardware = stream.shortSide > 1080)
        }

    private fun mimeOf(stream: VideoStream): String? {
        val codec = stream.codec?.lowercase()
        return when {
            codec == null -> if (stream.format == MediaFormat.MPEG_4) MimeTypes.VIDEO_H264 else null
            codec.startsWith("avc") -> MimeTypes.VIDEO_H264
            codec.startsWith("vp9") || codec.startsWith("vp09") -> MimeTypes.VIDEO_VP9
            codec.startsWith("av01") -> MimeTypes.VIDEO_AV1
            else -> null
        }
    }

    /** vp09.02… (profil 2) ou av01.x.xxX.10 : 10 bits, donc HDR chez YouTube. */
    private fun isHdr(stream: VideoStream): Boolean {
        val codec = stream.codec?.lowercase() ?: return false
        return codec.startsWith("vp09.02") || (codec.startsWith("av01") && codec.split('.').getOrNull(3) == "10")
    }

    /**
     * À qualité égale : AV1 (~40 % de données en moins que H.264) puis VP9 (~-40 % aussi, un peu
     * moins bon qu'AV1), s'ils sont décodés par une puce dédiée, la batterie est alors la même
     * qu'en H.264. Sinon H.264, et le décodage logiciel en dernier recours (gourmand).
     */
    private fun codecRank(stream: VideoStream): Int {
        val mime = mimeOf(stream) ?: return 0
        if (mime == MimeTypes.VIDEO_H264) return 3
        val hardware = stream.width > 0 && stream.height > 0 &&
            Decoders.supports(mime, stream.width, stream.height, stream.fps, needHardware = true)
        return when (mime) {
            MimeTypes.VIDEO_AV1 -> if (hardware) 5 else 1
            MimeTypes.VIDEO_VP9 -> if (hardware) 4 else 2
            else -> 0
        }
    }

    /**
     * Le codec à demander à yt-dlp pour un téléchargement en [height]p : « av01 », « vp9 » ou
     * « h264 », selon ce que le téléphone décode en matériel (même logique que la lecture).
     */
    fun preferredDownloadCodec(height: Int): String {
        val width = height * 16 / 9
        return when {
            Decoders.supports(MimeTypes.VIDEO_AV1, width, height, 30, needHardware = true) -> "av01"
            Decoders.supports(MimeTypes.VIDEO_VP9, width, height, 30, needHardware = true) -> "vp9"
            else -> "h264"
        }
    }

    private fun playableMuxed(info: StreamInfo): List<VideoStream> =
        info.videoStreams.filter { it.isUrl }

    /**
     * La meilleure piste audio, dans la langue d'origine. YouTube ajoute des doublages (souvent
     * générés par IA) et peut en mettre un par défaut selon la langue du téléphone : on les écarte,
     * comme l'audiodescription.
     */
    private fun bestAudio(streams: List<AudioStream>): AudioStream? {
        val playable = streams.filter { it.isUrl }
        val original = playable.filter { it.audioTrackType == AudioTrackType.ORIGINAL }
            // Vidéo à une seule piste : rien n'est étiqueté
            .ifEmpty { playable.filter { it.audioTrackType == null } }
            .ifEmpty { playable.filter { it.audioTrackType != AudioTrackType.DUBBED && it.audioTrackType != AudioTrackType.DESCRIPTIVE } }
            .ifEmpty { playable }
        return original.filter { it.format == MediaFormat.M4A }.maxByOrNull { it.averageBitrate }
            ?: original.maxByOrNull { it.averageBitrate }
    }
}

/** Ce que les décodeurs vidéo du téléphone savent faire (résultats gardés en mémoire). */
private object Decoders {
    private val cache = ConcurrentHashMap<String, Boolean>()

    fun supports(mime: String, width: Int, height: Int, fps: Int, needHardware: Boolean): Boolean =
        cache.getOrPut("$mime:$width:$height:$fps:$needHardware") { check(mime, width, height, fps, needHardware) }

    private fun check(mime: String, width: Int, height: Int, fps: Int, needHardware: Boolean): Boolean = runCatching {
        MediaCodecList(MediaCodecList.REGULAR_CODECS).codecInfos.any { info ->
            if (info.isEncoder || info.supportedTypes.none { it.equals(mime, ignoreCase = true) }) return@any false
            if (needHardware && !isHardware(info)) return@any false
            val video = info.getCapabilitiesForType(mime).videoCapabilities ?: return@any false
            val sizeOk = video.isSizeSupported(width, height) || video.isSizeSupported(height, width)
            val rateOk = fps <= 0 ||
                video.areSizeAndRateSupported(width, height, fps.toDouble()) ||
                video.areSizeAndRateSupported(height, width, fps.toDouble())
            sizeOk && rateOk
        }
    }.getOrDefault(false)

    private fun isHardware(info: MediaCodecInfo): Boolean =
        if (Build.VERSION.SDK_INT >= 29) info.isHardwareAccelerated
        else !info.name.startsWith("OMX.google.") && !info.name.startsWith("c2.android.")
}
